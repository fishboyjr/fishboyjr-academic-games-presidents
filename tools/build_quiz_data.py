"""Turn the parsed AGLOA Presidents Quiz archive (quiz_items.json from parse_quiz.py)
into js/data/quiz.js. Usage: python3 tools/build_quiz_data.py quiz_items.json js/data/quiz.js"""
import json, sys
items = json.load(open(sys.argv[1], encoding='utf-8'))
out = []
for it in items:
    t = ' '.join(it['text'].split()).replace('­', '')
    out.append({"t": t, "a": it['president'], "src": it['source'].replace('AGLOA ', ''), "url": it['url']})
with open(sys.argv[2], 'w', encoding='utf-8') as f:
    f.write('/*\n * Clues from the AGLOA monthly "Presidents Quiz" archive (2015-2021), https://agloa.org/category/pres-quiz/\n')
    f.write(' * Only clues whose answer is one of presidents #16-33. a: answer ("C" = Cleveland, either term).\n')
    f.write(' * Generated by tools/parse_quiz.py + tools/build_quiz_data.py - do not edit by hand.\n */\n')
    f.write('window.QUIZ_CLUES = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
print(len(out), 'clues written')
